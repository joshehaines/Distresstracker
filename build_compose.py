"""Bundle the app into a single self-contained docker-compose.yml.

Hostinger's Docker Manager deploys from compose contents alone (no build
context on the server), so the source travels inside the compose file as a
base64 tarball that the container unpacks at start-up. Secrets are NOT in
here: they come from the project's environment (.env) on the server.
"""
import base64
import io
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).parent
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tar:
    for p in sorted((ROOT / "app").rglob("*")):
        if p.is_file() and "__pycache__" not in p.parts:
            tar.add(p, arcname=str(p.relative_to(ROOT)))
    tar.add(ROOT / "requirements.txt", arcname="requirements.txt")
b64 = base64.b64encode(buf.getvalue()).decode()
chunks = "\n".join("      " + b64[i:i + 76] for i in range(0, len(b64), 76))

network = sys.argv[1] if len(sys.argv) > 1 else "nimb-cco_default"

compose = f"""# Case Alerts — generated by build_compose.py. Edit the source, not this file.
services:
  casealerts:
    image: python:3.12-slim
    restart: unless-stopped
    working_dir: /srv
    command:
      - sh
      - -c
      - |
        set -e
        mkdir -p /srv && cd /srv
        base64 -d /run/bundle.b64 | tar -xz
        if [ ! -f /venv/.ok ] || ! cmp -s requirements.txt /venv/requirements.txt; then
          python -m venv /venv && /venv/bin/pip install -q --no-cache-dir -r requirements.txt
          cp requirements.txt /venv/requirements.txt && touch /venv/.ok
        fi
        exec /venv/bin/uvicorn app.main:app --host 0.0.0.0 --port 8000 --proxy-headers --forwarded-allow-ips='*'
    environment:
      DATA_DIR: /data
      APP_NAME: ${{APP_NAME:-Case Alerts}}
      BASE_URL: ${{BASE_URL:-}}
      CH_API_KEY: ${{CH_API_KEY:-}}
      SECRET_KEY: ${{SECRET_KEY:?set SECRET_KEY}}
      ADMIN_EMAIL: ${{ADMIN_EMAIL:-}}
      ADMIN_PASSWORD: ${{ADMIN_PASSWORD:-}}
      ADMIN_NAME: ${{ADMIN_NAME:-Administrator}}
      COOKIE_SECURE: "1"
    configs:
      - source: bundle
        target: /run/bundle.b64
    volumes:
      - data:/data
      - venv:/venv
    networks:
      default: {{}}
      edge:
        aliases: [casealerts]
    healthcheck:
      test: ["CMD", "python", "-c", "import urllib.request;urllib.request.urlopen('http://127.0.0.1:8000/healthz')"]
      interval: 30s
      timeout: 5s
      start_period: 90s
      retries: 3

configs:
  bundle:
    content: |
{chunks}

volumes:
  data:
  venv:

networks:
  edge:
    external: true
    name: {network}
"""
out = ROOT / "deploy" / "docker-compose.yml"
out.parent.mkdir(exist_ok=True)
out.write_text(compose)
print(f"wrote {out} ({len(compose)//1024} KB, bundle {len(b64)//1024} KB)")
